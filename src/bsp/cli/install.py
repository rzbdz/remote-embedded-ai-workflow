"""`bsp install` — write ./SKILL.md for agents working in this directory.

The file is the generic bsp skill (skills/bsp-dev-loop/SKILL.md) with a short
generated section on top saying what this directory is (which configured SDK
targets live here), which boards can run them, and the hints of the active
configuration layers (packs, then the site: `<layer>/hints/*.md`), so an agent
can start without re-running `bsp sdk list` / `bsp dut list` / `bsp hints`.
The repo only provides the mechanism; every hint text comes from configuration.
"""

from __future__ import annotations

import os
import shutil
import time
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
SKILL_SRC = REPO / "skills" / "bsp-dev-loop" / "SKILL.md"


def _aliases(path: str, server_raw: dict[str, Any]) -> list[str]:
    """The path plus its spellings under the server's home aliases (/home/u == /data/home2/u)."""
    out = [os.path.realpath(path), path]
    homes = server_raw.get("home_aliases") or []
    for a in homes:
        for b in homes:
            if a != b and path.startswith(a.rstrip("/") + "/"):
                out.append(b.rstrip("/") + path[len(a.rstrip("/")):])
    return [p.rstrip("/") for p in out]


def matching_sdks(directory: Path, cat) -> list[Any]:
    """SDK instances whose workspace contains `directory` (deepest workspace first)."""
    here = os.path.realpath(directory).rstrip("/")
    hits = []
    for _, inst in sorted(cat.instances.items()):
        for p in _aliases(inst.path, inst.server.raw):
            rp = os.path.realpath(p).rstrip("/")
            if here == rp or here.startswith(rp + "/"):
                hits.append((len(rp), inst))
                break
    return [i for _, i in sorted(hits, key=lambda x: -x[0])]


def _sdk_lines(insts: list[Any]) -> list[str]:
    def one(i) -> str:
        boot = ", ".join(f"{m} {b.status}" for m, b in i.boot.items())
        return (f"`{i.id}` — {i.raw.get('description', '')} (SoC {i.soc}, workspace `{i.workspace.id}`, "
                f"dev repos {', '.join(f'`{p}`' for p in i.dev_projects) or '-'}, "
                f"components {', '.join(sorted(i.targets()))}, boot: {boot})")

    if len(insts) == 1:
        i = insts[0]
        out = [f"This directory is already configured as the SDK {one(i)}."]
    else:
        out = ["This directory is configured as these SDK targets:", ""] + [f"- {one(i)}" for i in insts]
    ws = {i.workspace.id for i in insts}
    out += ["", f"Work on it with `bsp sdk acquire {insts[0].id} --task <task> --holder <you>`; "
                f"one lease covers the whole workspace ({', '.join(sorted(ws))})."]
    return out


def _dut_lines(insts: list[Any], duts: list[dict[str, Any]] | None) -> list[str]:
    if duts is None:
        return ["Boards: no board host was reachable when this file was generated; run `bsp dut list`."]
    ids = {i.id for i in insts}
    socs = {i.soc for i in insts}
    rows = [d for d in duts if ids & set(d.get("sdks", [])) or d.get("soc") in socs]
    if not rows:
        return ["Boards: none of the reachable boards can run these SDKs (see `bsp dut list`)."]
    out = [f"Boards that can run {'it' if len(insts) == 1 else 'them'} "
           "(snapshot; check `bsp dut list --free` before leasing):", ""]
    for d in rows:
        out.append(f"- `{d['id']}` @ {d['host']}: {d['board']} (SoC {d.get('soc')}), sdks {', '.join(d['sdks'])}")
    return out


def _site():
    from ..core.site import site_dir

    return site_dir()


def _hint_lines(hints: list[tuple[str, str]]) -> list[str]:
    if not hints:
        return []
    out = ["", "## Hints from this installation's configuration", ""]
    for name, text in hints:
        out += [f"<!-- {name} -->", text, ""]
    return out


def render(directory: Path, cat, duts: list[dict[str, Any]] | None, bsp_path: str,
           hints: list[tuple[str, str]] | None = None) -> str:
    base = SKILL_SRC.read_text(encoding="utf-8")
    front, body = "", base
    if base.startswith("---"):
        end = base.index("---", 3) + 3
        front, body = base[:end], base[end:]
    insts = matching_sdks(directory, cat)
    gen = [f"## This workspace (generated by `bsp install` on {time.strftime('%Y-%m-%d %H:%M')})", "",
           f"Directory: `{os.path.realpath(directory)}` — `bsp` is `{bsp_path}`, "
           f"bsp repo (code, packs, hooks, skills) is `{REPO}`, site configuration is "
           f"`{_site() or 'not found'}`.", ""]
    if insts:
        gen += _sdk_lines(insts) + [""] + _dut_lines(insts, duts)
    else:
        gen += ["This directory is **not configured** as an bsp SDK yet. Do not guess: ask the user which",
                "SDK this is (or whether to add it), and check `bsp sdk list` for the configured ones.",
                "Board and console commands (`bsp dut ...`) still work for configured SDKs."]
    gen += _hint_lines(hints or [])
    gen += ["", "Below: the full bsp skill, copied unchanged.", "", "---", ""]
    return front + "\n\n" + "\n".join(gen) + body.lstrip("\n")


def install(directory: Path, cat, duts, bsp_path: str,
            hints: list[tuple[str, str]] | None = None) -> dict[str, Any]:
    target = Path(directory) / "SKILL.md"
    backup = None
    if target.exists():
        backup = target.with_name(f"SKILL.md.bak.{time.strftime('%Y%m%d-%H%M%S')}")
        shutil.copy2(target, backup)
    text = render(Path(directory), cat, duts, bsp_path, hints)
    target.write_text(text, encoding="utf-8")
    return {"file": str(target), "backup": str(backup) if backup else None,
            "sdks": [i.id for i in matching_sdks(Path(directory), cat)],
            "hints": [n for n, _ in hints or []]}
